#!/usr/bin/env python3
"""Codex adapter (compile-to-proposal only).

Usage: python adapters/codex.py --board <name> [--out DIR] [--codex-home DIR]

Prints a per-card feasibility table (native | static | unsupported) and writes
proposal files ONLY under adapters/codex/out/ (hooks fragment, AGENTS section).
It never writes to ~/.Codex; ~/.Codex/hooks.json is read (read-only) to decide
which hooks are already native. Realization is a manual owner step.
"""
import argparse, json, os, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WB = HERE.parent
OUT_DEFAULT = HERE / "codex" / "out"
CODEX_EVENTS = {"PreToolUse", "SessionStart", "UserPromptSubmit", "Stop"}


def load_board(name):
    sys.path.insert(0, str(WB))
    import registry as REG
    p = Path(REG.resolve(name[:-5] if name.endswith(".json") else name, str(WB / "boards")))
    return json.loads(p.read_text(encoding="utf-8"))


def installed_hook_files(codex_home):
    """Basenames of hook scripts already wired in Codex hooks.json (read-only)."""
    names = set()
    try:
        data = json.loads((Path(codex_home) / "hooks.json").read_text(encoding="utf-8"))
    except Exception:
        return names
    for groups in (data.get("hooks") or {}).values():
        for g in groups:
            for h in g.get("hooks", []):
                cmd = h.get("command", "")
                names.add(cmd.replace("\\", "/").rstrip("'\" ").rsplit("/", 1)[-1])
    return names


def classify(c, wired):
    t, r, mode = c["type"], c.get("ref", {}), c.get("execution_mode")
    if not c.get("enabled", True):
        return "static", "disabled card; documented only"
    if t == "hook":
        base = os.path.basename(r.get("file", ""))
        if base in wired:
            return "native", "hook script already wired in Codex hooks.json"
        if r.get("event") in CODEX_EVENTS:
            return "static", "Codex has the %s event; proposed hooks.json entry" % r.get("event")
        return "unsupported", "event %r has no Codex equivalent" % r.get("event")
    if mode == "enforce":
        if t == "agent" and r.get("verb") == "inject":
            return "unsupported", "Codex cannot inject/rewrite a subagent spawn (enforce inject)"
        if t == "gate":
            return "static", "enforce %s via a PreToolUse hook (proposal fragment)" % r.get("verb")
        return "unsupported", "enforce on %s not honorable by Codex" % t
    return "static", "observe-only; rendered as AGENTS.md prose"


def compile_board(board, codex_home):
    wired = installed_hook_files(codex_home)
    rows = []
    for c in board["cards"]:
        s, why = classify(c, wired)
        rows.append({"id": c["id"], "type": c["type"], "mode": c["execution_mode"], "status": s, "why": why, "card": c})
    return rows


def render_table(rows):
    w = max(len(r["id"]) for r in rows)
    lines = ["%-*s  %-8s %-8s %-11s %s" % (w, "card", "type", "mode", "codex", "note")]
    for r in rows:
        lines.append("%-*s  %-8s %-8s %-11s %s" % (w, r["id"], r["type"], r["mode"], r["status"], r["why"]))
    return "\n".join(lines)


def hooks_fragment(rows):
    frag = {"_comment": "PROPOSAL ONLY - generated by workflow-board adapters/codex.py; merge manually", "hooks": {}}
    for r in rows:
        c = r["card"]
        if r["status"] == "static" and c["type"] == "hook" and c["enabled"]:
            ev = c["ref"]["event"]
            entry = {"hooks": [{"type": "command", "command": "bash '%s'" % c["ref"]["file"]}]}
            if c["ref"].get("matcher"):
                entry["matcher"] = c["ref"]["matcher"]
            frag["hooks"].setdefault(ev, []).append(entry)
        elif r["status"] == "static" and c["type"] == "gate" and c["enabled"]:
            frag["hooks"].setdefault("PreToolUse", []).append(
                {"matcher": ".*", "hooks": [{"type": "command", "command": "bash '<write gate script for: %s>'" % c["ref"].get("rule", "")}]})
    return frag


def agents_section(board, rows):
    out = ["## Workflow board: %s (proposed, generated)" % board["board"], "",
           "Generated by workflow-board adapters/codex.py. Proposal only; paste manually if approved.", ""]
    for r in rows:
        c = r["card"]
        out.append("- [%s/%s] %s: %s" % (r["status"], r["mode"], c["type"], c["label"]))
    uns = [r for r in rows if r["status"] == "unsupported"]
    if uns:
        out += ["", "Not honorable on Codex: " + ", ".join(r["id"] for r in uns)]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", required=True)
    ap.add_argument("--out", default=str(OUT_DEFAULT))
    ap.add_argument("--codex-home", default=str(Path.home() / ".Codex"))
    a = ap.parse_args(argv)
    out = Path(a.out).resolve()
    home = os.path.normcase(str((Path.home() / ".Codex").resolve()))
    if os.path.normcase(str(out)).startswith(home) or os.path.normcase(str(out)).startswith(os.path.normcase(str(Path(a.codex_home).resolve()))):
        print("refusing to write under the Codex home", file=sys.stderr)
        return 2
    board = load_board(a.board)
    rows = compile_board(board, a.codex_home)
    print(render_table(rows))
    counts = {k: sum(1 for r in rows if r["status"] == k) for k in ("native", "static", "unsupported")}
    print("\nsummary: %s" % counts)
    out.mkdir(parents=True, exist_ok=True)
    stem = board["board"]
    (out / (stem + ".hooks.fragment.json")).write_text(json.dumps(hooks_fragment(rows), indent=2) + "\n", encoding="utf-8")
    (out / (stem + ".AGENTS.section.md")).write_text(agents_section(board, rows), encoding="utf-8")
    print("wrote proposals under %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
