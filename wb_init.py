#!/usr/bin/env python3
"""wb_init: build boards from a folder of agent files, without clobbering boards you edited (stdlib only).

  python wb_init.py --from DIR [--importer NAME] [--out DIR] [--force] [importer options]

The files in DIR stay the system of record; boards are a derived view. Read-only on DIR. Writes only to --out
(default: the first folder in WB_BOARD_DIRS, else ~/.workflow-board/boards). Point serve.py at the same folder with
WB_BOARD_DIRS so the boards appear in the picker.

No-clobber. Each generated board records the semantic hash it was written with (generated.board_sha). On the next run:
  - unchanged since generation -> regenerated in place, keeping your layout (positions, sizes, colours, lane styles)
    and any sticky-note cards you added
  - edited since generation (cards, edges or fields changed) -> left alone and listed in <out>/.wb-init-conflicts.json
  - a board of the same name that this tool did not generate -> left alone and listed
  --force overwrites conflicts after copying the old file to <out>/.wb-init-backup/.
Exit 0 when every board was written or unchanged, 3 when there were conflicts, 2 when a board failed validation.

Importers live in importers/ (see importers/__init__.py). Today: tpm-portfolio (options --sops, --include-archived).
"""
import argparse
import json
import os
import shutil
import sys
import tempfile
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import importers  # noqa: E402
import serve_v4_runs as R  # noqa: E402  (semantic hash + card diff, shared with the canvas dirty badge)
import validate as V  # noqa: E402

LAYOUT_CARD = ("pos", "size", "style", "pin")


def default_out():
    dirs = [d for d in (os.environ.get("WB_BOARD_DIRS") or "").split(os.pathsep) if d]
    return dirs[0] if dirs else os.path.join(os.path.expanduser("~"), ".workflow-board", "boards")


def board_sha(doc):
    """Semantic hash of a board without its `generated` block (layout and sticky notes do not count)."""
    return R.semantic_hash({k: v for k, v in doc.items() if k != "generated"})


def _atomic_write(path, doc):
    d = os.path.dirname(path)
    fd, tmp = tempfile.mkstemp(prefix=".wb-", dir=d)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(doc, f, indent=2)
            f.write("\n")
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):  # dump or replace failed: leave no .wb-* litter in the boards folder
            try:
                os.unlink(tmp)
            except OSError:
                pass


def carry_layout(new, old):
    """Keep the user's layout and sticky notes from the previous generation."""
    oc = {c["id"]: c for c in old.get("cards", []) if isinstance(c, dict)}
    for c in new["cards"]:
        o = oc.get(c["id"])
        if o:
            for k in LAYOUT_CARD:
                if k in o:
                    c[k] = o[k]
    if old.get("group_styles"):
        new["group_styles"] = old["group_styles"]
    ids = {c["id"] for c in new["cards"]}
    notes = [c for c in old.get("cards", []) if c.get("type") == "note" and c["id"] not in ids]
    new["cards"].extend(notes)
    note_ids = {c["id"] for c in notes}
    new["edges"].extend(e for e in old.get("edges", []) if R._end_id(e.get("from")) in note_ids or R._end_id(e.get("to")) in note_ids)
    return new


def plan_write(name, doc, out):
    """-> (action, doc_to_write | None, detail). action: create | update | unchanged | conflict."""
    path = os.path.join(out, name + ".json")
    gen = doc.setdefault("generated", {})
    gen["board_sha"] = board_sha(doc)
    if not os.path.isfile(path):
        return "create", doc, None
    try:
        with open(path, encoding="utf-8") as f:
            old = json.load(f)
    except (OSError, ValueError) as e:
        return "conflict", None, f"existing file unreadable: {e}"
    og = old.get("generated") if isinstance(old, dict) else None
    if not isinstance(og, dict) or "board_sha" not in og:
        return "conflict", None, "a board with this name exists and was not generated by wb_init"
    if og["board_sha"] != board_sha(old):
        return "conflict", None, {"edited_since_generation": True, "your_board_vs_new_import": R.diff_boards(old, doc)}
    if og["board_sha"] == gen["board_sha"] and old.get("generated", {}).get("sources") == gen.get("sources"):
        return "unchanged", None, None
    return "update", carry_layout(doc, old), None


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--from", dest="src", help="folder of agent files to import")
    ap.add_argument("--portfolio", dest="src_alias", help=argparse.SUPPRESS)  # pre-PR-3 spelling
    ap.add_argument("--importer", choices=sorted(importers.IMPORTERS), help="default: auto-detect")
    ap.add_argument("--out", default=None)
    ap.add_argument("--force", action="store_true", help="overwrite conflicting boards (old file is backed up)")
    ap.add_argument("--sops", action="append", default=[], metavar="DIR", help="tpm-portfolio: folder of *.sop.md files")
    ap.add_argument("--include-archived", action="store_true", help="tpm-portfolio: include ARCHIVED projects")
    a = ap.parse_args(argv)
    src = a.src or a.src_alias
    if not src or not os.path.isdir(src):
        ap.error("--from DIR is required and must be a folder")
    mod = importers.get(a.importer) if a.importer else importers.detect(src)
    if not mod:
        print(f"no importer recognises {src} (known: {', '.join(importers.IMPORTERS)})", file=sys.stderr)
        return 2
    orig_dirs = [os.path.abspath(d) for d in (os.environ.get("WB_BOARD_DIRS") or "").split(os.pathsep) if d]
    out = os.path.abspath(os.path.expanduser(a.out or default_out()))
    os.makedirs(out, exist_ok=True)
    boards = mod.build(src, {"sops": a.sops, "include_archived": a.include_archived})
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    counts, conflicts = {"create": 0, "update": 0, "unchanged": 0, "conflict": 0, "forced": 0}, []
    for name, doc in boards.items():
        doc["saved_at"] = now
        doc.setdefault("generated", {})["generated_at"] = now
        action, wdoc, detail = plan_write(name, doc, out)
        if action == "conflict" and a.force:
            bdir = os.path.join(out, ".wb-init-backup")
            os.makedirs(bdir, exist_ok=True)
            p = os.path.join(out, name + ".json")
            if os.path.isfile(p):
                shutil.copy2(p, os.path.join(bdir, f"{name}.{now.replace(':', '')}.json"))
            action, wdoc = "forced", doc
        counts[action] += 1
        if action == "conflict":
            conflicts.append({"board": name, "path": os.path.join(out, name + ".json"), "reason": detail})
        elif wdoc is not None:
            _atomic_write(os.path.join(out, name + ".json"), wdoc)
    report = os.path.join(out, ".wb-init-conflicts.json")
    if conflicts:
        _atomic_write(report, {"generated_at": now, "importer": mod.NAME, "conflicts": conflicts})
    elif os.path.isfile(report):
        os.remove(report)
    os.environ["WB_BOARD_DIRS"] = os.pathsep.join([out] + [d for d in (os.environ.get("WB_BOARD_DIRS") or "").split(os.pathsep) if d and d != out])
    bad = []
    for name in boards:
        p = os.path.join(out, name + ".json")
        try:
            with open(p, encoding="utf-8") as f:
                V.validate_doc(json.load(f), name)
        except (OSError, ValueError, V.Invalid) as e:
            bad.append(f"{name}: {e}")
    print(f"{mod.NAME}: {len(boards)} boards in {out} - {counts['create']} new, {counts['update']} updated, "
          f"{counts['unchanged']} unchanged, {counts['conflict']} conflicts" + (f", {counts['forced']} forced" if counts["forced"] else ""))
    for c in conflicts:
        print(f"  conflict {c['board']}: {c['reason'] if isinstance(c['reason'], str) else 'edited since generation'}", file=sys.stderr)
    if conflicts:
        print(f"  kept your versions; details in {report}. Re-run with --force to overwrite (backups kept).", file=sys.stderr)
    if out not in orig_dirs:
        print(f"  serve.py finds these boards when WB_BOARD_DIRS includes {out}", file=sys.stderr)
    if bad:
        print("INVALID boards:\n  " + "\n  ".join(bad), file=sys.stderr)
        return 2
    return 3 if conflicts else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
